def loop_partials(
    loop_len: int, count: int, *, rate: int, f0: float
) -> list[float]:
    """Partial frequencies that complete a WHOLE number of cycles in the loop.

    The fix for a buzzing sustain. A looping sample is only seamless if every
    partial it contains is periodic over the loop length, and the first
    version of this bank detuned its partials by up to eleven cents, which
    makes that impossible by construction: the partials no longer share the
    loop's period, so the waveform jumps at every wrap.

    Measured, that jump was 4x to 12x a normal sample-to-sample step, once per
    loop -- 32.7 Hz for the sustained instruments. A discontinuity repeating at
    32.7 Hz is a 32.7 Hz tone, which is what "feedback or something coming
    through" was.

    Crossfading the boundary is the usual patch and it was attempted, but it
    was applied to the wrong place: the buffer's end was blended into its
    start, while the player wraps from `loop_end` back to `loop_start`. Making
    the partials exactly periodic removes the discontinuity instead of
    smearing it, and needs no crossfade at all.
    """
    out: list[float] = []
    for index in range(1, count + 1):
        cycles = max(1, round(f0 * index * loop_len / rate))
        out.append(cycles * rate / loop_len)
    return out


def render_sample(
    instrument: Instrument, *, rate: int = BANK_RATE, seed: int = 0
) -> tuple[np.ndarray, int, int]:
    """Synthesise one instrument's sample.

    Returns `(samples, loop_start, loop_end)`. A non-looping instrument gets
    `loop_start == loop_end == 0`, which the sampler reads as one-shot.
    """
    # zlib.crc32, not hash(): Python randomises string hashing per process
    # unless PYTHONHASHSEED is fixed, so seeding from hash() made the sample
    # bank -- and therefore every rendered WAV -- different on every run. The
    # determinism requirement caught it.
    rng = np.random.default_rng(seed + zlib.crc32(instrument.name.encode()))
    f0 = midi_to_hz(instrument.root_note)

    if not instrument.looping:
        count = int(instrument.oneshot_sec * rate)
        t = np.arange(count, dtype=np.float64) / rate
        wave = np.zeros(count, dtype=np.float64)
        # A falling pitch, integrated so the phase stays continuous: stepping
        # the frequency per sample without integrating produces a buzz.
        if instrument.pitch_drop:
            decay = max(1e-4, instrument.envelope.decay)
            factor = 2.0 ** (-instrument.pitch_drop * np.minimum(1.0, t / decay))
            phase_t = np.cumsum(factor) / rate
        else:
            phase_t = t
        for index, amplitude in enumerate(instrument.harmonics, start=1):
            wave += amplitude * np.sin(2 * math.pi * f0 * index * phase_t)
        if instrument.noise:
            # Percussion is mostly noise; a little low-passing stops the hat
            # sounding like pure white static.
            noise = rng.standard_normal(count)
            kernel = np.ones(3) / 3.0
            noise = np.convolve(noise, kernel, mode="same")
            wave = wave * (1.0 - instrument.noise) + noise * instrument.noise
        # A one-shot carries its own decay: the sampler does not loop it, so
        # the shape has to be in the data.
        decay = np.exp(-t / max(1e-4, instrument.envelope.decay))
        wave *= decay
        wave -= wave.mean()
        peak = np.abs(wave).max() or 1.0
        return (wave / peak).astype(np.float32), 0, 0

    # Looping. The loop is generated as an exactly periodic waveform, so the
    # wrap is seamless without any crossfade.
    cycle = rate / f0
    loop_len = int(round(cycle * instrument.loop_cycles))
    lead = int(round(cycle * 2))

    frequencies = loop_partials(
        loop_len, len(instrument.harmonics), rate=rate, f0=f0
    )
    # Phase offsets are loop-safe -- a phase shift of a periodic wave is still
    # periodic -- so the ensemble character comes from phase and from the
    # harmonic recipe rather than from detuning, which is not.
    phases = [
        rng.uniform(0, 2 * math.pi) if instrument.spread_cents else 0.0
        for _ in instrument.harmonics
    ]

    # The loop body first, then the attack lead-in built from the same
    # waveform, so the lead-in runs continuously into the loop.
    total = lead + loop_len
    t = np.arange(total, dtype=np.float64) / rate
    wave = np.zeros(total, dtype=np.float64)
    for amplitude, hz, phase in zip(
        instrument.harmonics, frequencies, phases, strict=True
    ):
        wave += amplitude * np.sin(2 * math.pi * hz * t + phase)

    # No noise in a looping instrument. Noise cannot be periodic, so it either
    # clicks at the wrap or -- if tiled to the loop length, which was the first
    # attempt -- becomes a pitched rasp at the loop rate rather than noise. It
    # was only 1-2% of the signal and it was audible as an artifact, so
    # sustained instruments are purely harmonic and percussion keeps its noise,
    # which is fine because percussion is one-shot and never loops.

    # Remove DC over the LOOP region, which is what a held note repeats. An
    # additive stack with random partial phases has a non-zero mean, and a
    # constant offset under every sustained note wastes headroom and reads as
    # pressure rather than tone. The finished mix measured +0.012 DC before
    # this.
    wave -= wave[lead:total].mean()
    peak = np.abs(wave).max() or 1.0
    return (wave / peak).astype(np.float32), lead, total


@dataclass
class SampleAsset:
    """A rendered sample and everything needed to play and account for it."""

    instrument: Instrument
    data: np.ndarray
    rate: int
    loop_start: int
    loop_end: int

    @property
    def frames(self) -> int:
        return int(self.data.size)

    @property
    def pcm_bytes(self) -> int:
        """Prototype cost: 16-bit PCM."""
        return self.frames * 2

    @property
    def brr_estimate_bytes(self) -> int:
        """What the data would cost encoded as BRR.

        An ESTIMATE from the format's geometry -- 9 bytes per 16 samples --
        and not a measurement of encoded data. Nothing here is BRR-encoded.
        """
        return math.ceil(self.frames / 16) * 9

    def to_dict(self) -> dict[str, Any]:
        return {
            **self.instrument.to_dict(),
            "rate": self.rate,
            "frames": self.frames,
            "loop_start": self.loop_start,
            "loop_end": self.loop_end,
            "looping": self.loop_end > self.loop_start,
            "pcm_bytes": self.pcm_bytes,
            "brr_estimate_bytes": self.brr_estimate_bytes,
        }


def calibrate(assets: dict[str, SampleAsset]) -> dict[str, float]:
    """Per-instrument gains so equal velocity means comparable loudness.

    The lesson from the NES balance defect, applied before it can happen
    again: a brass sample and a hat sample at the same numeric velocity are
    nowhere near the same loudness, because loudness follows the waveform's
    RMS and not its peak. Peak-normalising each sample -- which
    `render_sample` already does -- equalises the wrong quantity.

    Measured over the LOOP REGION for sustained instruments, because that is
    what a held note actually sounds, and over the whole one-shot for
    percussion. Reference is the brass lead at 1.0, since the lead is the part
    everything else is balanced against.
    """
    levels: dict[str, float] = {}
    for name, asset in assets.items():
        if asset.loop_end > asset.loop_start:
            region = asset.data[asset.loop_start : asset.loop_end]
        else:
            region = asset.data
        if region.size == 0:
            levels[name] = 0.0
            continue
        levels[name] = float(np.sqrt(np.mean(np.square(region.astype(np.float64)))))
    reference = levels.get("brass") or (max(levels.values()) or 1.0)
    return {
        name: float(reference / level) if level > 1e-9 else 1.0
        for name, level in levels.items()
    }


def build_bank(
    *, rate: int = BANK_RATE, seed: int = 0, brr: bool = True
) -> dict[str, SampleAsset]:
    """Render every instrument, with calibrated gains applied.

    `brr=True` passes every sample through a real BRR encode and decode, so
    the bank carries the format's quantisation. That is the point of BRR
    beyond byte counts: a 4-bit residual over a 2-tap predictor is lossy in a
    specific way, and a preview playing clean PCM does not sound like a SNES
    even when the samples and the mixing are right. Measured cost is 0.12% to
    1.21% RMS, highest on the noise-heavy percussion, which is correct --
    noise is exactly what a linear predictor cannot predict.
    """
    assets = {
        name: SampleAsset(
            instrument=instrument,
            data=data,
            rate=rate,
            loop_start=start,
            loop_end=end,
        )
        for name, instrument in BANK.items()
        for data, start, end in [render_sample(instrument, rate=rate, seed=seed)]
    }
    if brr:
        from rse.snes.brr import decode as brr_decode
        from rse.snes.brr import encode as brr_encode

        quantised: dict[str, SampleAsset] = {}
        for name, asset in assets.items():
            loop = asset.loop_start if asset.loop_end > asset.loop_start else None
            encoded = brr_encode(asset.data, loop_start=loop)
            # Decode back to the ORIGINAL length: the encoder pads to a whole
            # block and playing the padding would add a click at the end.
            data = brr_decode(encoded, frames=asset.frames).astype(np.float32)
            quantised[name] = SampleAsset(
                instrument=asset.instrument,
                data=data,
                rate=asset.rate,
                loop_start=asset.loop_start,
                loop_end=asset.loop_end,
            )
        assets = quantised

    gains = calibrate(assets)
    out: dict[str, SampleAsset] = {}
    for name, asset in assets.items():
        # Percussion is deliberately left near its own level: calibrating a
        # hat to a brass note's RMS makes it a cymbal crash.
        gain = gains[name] if asset.instrument.looping else 1.0
        out[name] = SampleAsset(
            instrument=dataclasses.replace(asset.instrument, gain=gain),
            data=asset.data,
            rate=asset.rate,
            loop_start=asset.loop_start,
            loop_end=asset.loop_end,
        )
    return out


def manifest(assets: dict[str, SampleAsset], *, encoded: dict | None = None) -> dict[str, Any]:
    """The bank's provenance and memory report.

    `encoded` supplies real `BrrSample`s, which turns the memory figures from
    estimates into measurements.
    """
    total_pcm = sum(a.pcm_bytes for a in assets.values())
    if encoded:
        total_brr = sum(e.size_bytes for e in encoded.values())
    else:
        total_brr = sum(a.brr_estimate_bytes for a in assets.values())
    return {
        "bank_id": "rse-snes-prototype/0.1",
        "provenance": (
            "Original synthesised prototype instruments, generated from the "
            "additive recipes in rse/snes/samples.py. No commercial or "
            "third-party sample data."
        ),
        "rate": BANK_RATE,
        "instrument_count": len(assets),
        "instruments": {name: asset.to_dict() for name, asset in assets.items()},
        "pcm_bytes": total_pcm,
        "brr_bytes": total_brr,
        "brr_measured": bool(encoded),
        "aram_total_bytes": 65536,
        "brr_fraction_of_aram": round(total_brr / 65536, 4),
        "caveat": (
            "Sample bytes are MEASURED from real BRR encoding. Hardware "
            "compatibility is still not claimed: a correct byte count is not "
            "an SPC file and no emulator has run any of this."
            if encoded
            else "brr_estimate_bytes is computed from the format's geometry. "
            "Nothing in this bank is BRR-encoded."
        ),
    }
