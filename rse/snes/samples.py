"""A small bank of original instrument samples, synthesised in-repository.

Prototype instruments, not commercial game samples. Every waveform here is
generated by the code below from additive synthesis and shaped noise, so the
bank is reproducible from source, carries no licence question, and needs no
binary assets in the repository.

Each instrument is defined by its harmonic recipe and its envelope, because
those are what make a sampled instrument recognisable. A brass sample is not a
string sample with a different name: brass has strong low harmonics and a
slightly slow attack, strings have a dense upper spectrum and a soft one,
percussion is shaped noise with no loop at all.

Loop points matter as much as the spectrum. A sustained instrument has to loop
cleanly or every held note clicks, so the loop region is placed on a whole
number of cycles of the fundamental and crossfaded. Percussion is one-shot and
declares no loop.

What this is NOT: BRR-encoded, 64 KiB-budgeted, or S-DSP-accurate. The sizes
reported here are the PCM prototype's, and `brr_estimate_bytes` is an estimate
of what the data would cost after encoding, not a measurement of encoded data.
"""

from __future__ import annotations

import dataclasses
import math
import zlib
from dataclasses import dataclass
from typing import Any

import numpy as np

#: Sample rate the prototype bank is generated and played at.
#:
#: Not 32 kHz. The S-DSP's nominal output rate is 32 kHz, but that is the rate
#: the hardware mixes at, not a rate a sample asset must be recorded at, and
#: the preview renderer runs at CD rate so its output needs no resampling
#: before export.
BANK_RATE = 32000

#: Concert A, for tuning.
A4_HZ = 440.0
A4_MIDI = 69


@dataclass(frozen=True)
class Envelope:
    """ADSR in seconds, with sustain as a level.

    Modelled on the S-DSP's envelope stages -- key-on runs attack then decay to
    the sustain level, and key-off starts the release -- but computed in
    floating point rather than with the hardware's rate tables. The shape is
    hardware-informed; it is not hardware-exact.
    """

    attack: float
    decay: float
    sustain: float
    release: float

    def to_dict(self) -> dict[str, float]:
        return {
            "attack": self.attack,
            "decay": self.decay,
            "sustain": self.sustain,
            "release": self.release,
        }


@dataclass(frozen=True)
class Instrument:
    """One sampled instrument."""

    name: str
    #: Harmonic amplitudes, index 0 being the fundamental.
    harmonics: tuple[float, ...]
    envelope: Envelope
    #: MIDI note the recorded sample sounds at.
    root_note: int
    #: Whether the sample loops while a key is held.
    looping: bool
    #: Per-instrument gain, calibrated so instruments at the same velocity
    #: sound comparably loud. See `calibrate` for why this is measured rather
    #: than guessed.
    gain: float = 1.0
    #: Default stereo position, -1 hard left to +1 hard right.
    pan: float = 0.0
    #: Inharmonic noise mixed in, for percussion and breathy attacks.
    noise: float = 0.0
    #: Cycles of the fundamental held in the loop region.
    loop_cycles: int = 16
    #: Seconds of one-shot material for a non-looping instrument.
    oneshot_sec: float = 0.35
    #: Octaves the pitch falls across a one-shot's decay.
    #:
    #: What makes a kick a kick. Without it a kick is a short tone plus noise,
    #: and with 10% noise the spectral centroid came out at 2706 Hz -- for a
    #: drum whose fundamental should sit near 65 Hz. The drop is the gesture.
    pitch_drop: float = 0.0
    #: Slight detune between partials, which is most of what makes an
    #: ensemble sound like several players rather than one.
    spread_cents: float = 0.0

    def to_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "root_note": self.root_note,
            "looping": self.looping,
            "harmonics": list(self.harmonics),
            "envelope": self.envelope.to_dict(),
            "gain": round(self.gain, 4),
            "pan": self.pan,
            "noise": self.noise,
            "spread_cents": self.spread_cents,
        }


def midi_to_hz(note: int) -> float:
    return A4_HZ * (2.0 ** ((note - A4_MIDI) / 12.0))


