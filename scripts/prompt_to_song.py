"""Prompt-to-Song v0.1: free text in, a complete NES track out.

End to end: a written request becomes a plan the composer can take, the
composer writes the musical material, the assembler builds a full-length form
out of it, and the existing corrected pipeline renders it as hardware-valid
NES audio.

The form is A A' B A'', each section eight bars:

- **A** is generated fresh from the plan's conditioning.
- **A'** and **A''** are generated by handing the model A's first four bars as
  a prefix and letting it continue. So the returning material is genuinely
  re-composed around the same opening rather than pasted -- the mechanism
  validated in `scripts/theme_bank.py`, where every prefix resumed cleanly at
  the next bar.
- **B** is generated fresh with a deliberately altered key, which is what
  makes it contrast. The model is not asked for "a contrasting section"; it
  cannot be. The contrast comes from changing its conditioning.

**What is generated and what is imposed is reported, not blurred.** The
composer never receives "contrasting middle section", "return to the main
theme" or "loopable". Those are structural decisions this script makes. The
report separates requirements that were satisfied, approximated, imposed by
the assembler, and simply unsupported -- and "memorable melody" is always in
the last group, because nothing anywhere in this pipeline takes memorability
as an input.

The loop is a real boundary rather than a fade: the track is rendered to end
exactly at the final bar line with the loop points recorded, so the last bar
runs straight into the first.

v0.1 does not claim the output is good. It claims the output is complete,
hardware-valid, the requested length, and honestly described.
"""

from __future__ import annotations

import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

import argparse
import dataclasses
import json
from typing import Any

from rse.analysis.restatement import ticks_per_bar
from rse.codec.benchmark import enforce_monophony
from rse.events.schema import Composition, TempoChange, TimeSignatureChange
from rse.hardware.constraints import ConstraintEngine
from rse.hardware.profile import load_profile
from rse.prompt.interpret import Requirement, SongPlan, interpret
from rse.tokenizers.frozen import frozen_config
from rse.tokenizers.tokenizer import GridFit, RseTokenizer
from rse.transfer.arranger import arrange_for_nes, row_seconds
from rse.transfer.fermata import Vocab, decode, trim_to_bars

ROW_SEC = 0.1
SECTION_BARS = 8
THEME_BARS = 4
PEAK_DBFS = -3.0

#: Key offset for the contrasting section. A fifth away is the conventional
#: move and is expressible in the composer's `<KEY_root:mode>` family.
CONTRAST_KEY_OFFSET = 1


def build_header(vocab: Vocab, plan: SongPlan, *, key_root: int | None = None) -> list[str]:
    """The composer's header for this plan.

    Built here rather than reusing `fermata_generate.build_header`, because
    that one takes a fixed scenario dict and this has to carry an interpreted
    plan with an overridable key.
    """
    root = plan.key_root if key_root is None else key_root
    tempo = min(vocab.tempos, key=lambda t: abs(t - plan.tempo_bpm))
    key = f"<KEY_{root}:{plan.key_mode}>"
    if key not in vocab.token_to_id:
        key = f"<KEY_{root}:minor>"
    meter = f"<METER_{plan.beats_per_bar}/4>"
    if meter not in vocab.token_to_id:
        meter = "<METER_4/4>"
    header = [
        "<BOS>",
        f"<GENRE_{plan.genre}>",
        f"<ENSEMBLE_{plan.ensemble}>",
        f"<TEMPO_{tempo}>",
        key,
        meter,
        "<PLAN>",
        *plan.plan_tokens(),
        "<PLAN_END>",
    ]
    return [t for t in header if t in vocab.token_to_id]


def bar_prefix(ids: list[int], *, vocab: Vocab, n_bars: int) -> list[int] | None:
    """Stream cut just before the token opening bar `n_bars + 1`, no EOS."""
    bar_id = vocab.id_of("<BAR>")
    implicit = False
    for token_id in ids:
        if token_id == bar_id:
            break
        if vocab.id_to_token.get(token_id, "").startswith(("<PITCH_", "<DRUM_NOTE_")):
            implicit = True
            break
    seen = 1 if implicit else 0
    for index, token_id in enumerate(ids):
        if token_id == bar_id:
            seen += 1
            if seen == n_bars + 1:
                return ids[:index]
    return None


def concatenate(
    sections: list[Composition], *, bar_ticks: int, section_bars: int, bpm: float,
    beats_per_bar: int,
) -> Composition:
    """Lay sections end to end on bar lines and mark the loop.

    Each section is placed at its own bar offset, so a section that ended
    early does not shorten the one after it -- the form stays metrically
    correct even when the composer left its last bar sparse.
    """
    events = []
    for index, section in enumerate(sections):
        offset = index * section_bars * bar_ticks
        for event in section.sounding_events():
            events.append(dataclasses.replace(event, tick=event.tick + offset))
    track = Composition(
        hardware_profile="nes", ticks_per_beat=section.ticks_per_beat, events=events
    )
    track.tempo_map = [TempoChange(0, int(round(60_000_000 / bpm)))]
    track.time_signatures = [TimeSignatureChange(0, beats_per_bar, 4)]
    # A real boundary, not a fade: the loop runs from the first bar line to
    # the last, so the final bar leads straight back into the opening.
    track.loop_start_tick = 0
    track.loop_end_tick = len(sections) * section_bars * bar_ticks
    track.normalize()
    return track


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "prompt",
        nargs="?",
        default=(
            "Compose a 60-second NES-era JRPG battle theme. Dark and ominous "
            "but energetic, with a memorable opening melody, driving "
            "percussion, a contrasting middle section and a return to the "
            "main theme. Make it seamlessly loopable."
        ),
    )
    parser.add_argument("--model", type=Path, default=Path("/tmp/fermata_dl"))
    parser.add_argument("--seed", type=int, default=20261026)
    parser.add_argument("--max-attempts", type=int, default=6)
    parser.add_argument("--temperature", type=float, default=0.7)
    parser.add_argument("--top-k", type=int, default=24)
    parser.add_argument("--repetition-penalty", type=float, default=1.12)
    parser.add_argument("--max-new-tokens", type=int, default=2000)
    parser.add_argument("--out-dir", type=Path, default=Path("songs"))
    parser.add_argument("--name", default="song_v01")
    args = parser.parse_args()

    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import torch
    from architecture_comparison import normalise_peak
    from codec_comparison import render_window
    from transformers import LlamaForCausalLM
    from transformers.generation.logits_process import LogitsProcessor

    plan = interpret(args.prompt)
    total_bars = plan.bars_for_target(section_bars=SECTION_BARS)
    n_sections = max(2, total_bars // SECTION_BARS)
    # A A' B A'' when there is room; the B slot is the second from last.
    roles = ["A"] + ["A'"] * max(0, n_sections - 3) + (["B", "A''"] if n_sections >= 3 else [])
    roles = roles[:n_sections]
    if n_sections >= 3:
        roles = ["A"] + ["A'"] * (n_sections - 3) + ["B", "A''"]

    print(f"prompt: {args.prompt}\n")
    print(f"plan: {plan.genre}/{plan.ensemble}, {plan.tempo_bpm} BPM, key "
          f"{plan.key_token}, {plan.beats_per_bar}/4")
    print(f"      {plan.plan_tokens()}")
    print(f"form: {' '.join(roles)}  ({n_sections} x {SECTION_BARS} bars = "
          f"{total_bars} bars, {total_bars * plan.seconds_per_bar:.1f} s; "
          f"requested {plan.target_seconds:g} s)\n")

    vocab = Vocab.load(args.model / "tokenizer" / "vocab.json")
    model = LlamaForCausalLM.from_pretrained(args.model, dtype=torch.float32).eval()

    class SuppressBpe(LogitsProcessor):
        def __init__(self, ids: list[int]) -> None:
            self.ids = torch.tensor(ids, dtype=torch.long)

        def __call__(self, _input_ids, scores):
            scores[:, self.ids] = float("-inf")
            return scores

    class StopAfterBars(torch.nn.Module):
        def __init__(self, bar_id: int, offset: int, n_bars: int) -> None:
            super().__init__()
            self.bar_id = bar_id
            self.offset = offset
            self.limit = n_bars + 1

        def __call__(self, input_ids, _scores, **_kwargs) -> bool:
            return bool((input_ids[0] == self.bar_id).sum() + self.offset >= self.limit)

    processors = [SuppressBpe(vocab.bpe_ids)]
    tokenizer = RseTokenizer(frozen_config())
    profile = load_profile("nes")
    engine = ConstraintEngine(profile)
    bar_ticks = ticks_per_bar()

    def generate(prompt_ids: list[int], *, seed: int, offset: int) -> list[int]:
        torch.manual_seed(seed)
        with torch.no_grad():
            out = model.generate(
                torch.tensor([prompt_ids]),
                do_sample=True,
                temperature=args.temperature,
                top_k=args.top_k,
                repetition_penalty=args.repetition_penalty,
                max_new_tokens=args.max_new_tokens,
                eos_token_id=vocab.id_of("<EOS>"),
                pad_token_id=vocab.id_of("<PAD>"),
                logits_processor=processors,
                stopping_criteria=[
                    StopAfterBars(vocab.id_of("<BAR>"), offset, SECTION_BARS)
                ],
                use_cache=True,
            )
        return out[0].tolist()

    def to_nes(ids: list[int]) -> tuple[Composition, dict[str, Any]] | None:
        trimmed = trim_to_bars(ids, vocab=vocab, n_bars=SECTION_BARS)
        if not (trimmed.complete and trimmed.n_bars == SECTION_BARS):
            return None
        score, decode_report = decode(trimmed.ids, vocab=vocab)
        arranged, arrange_report = arrange_for_nes(
            score, row_sec=ROW_SEC, divisions=tokenizer.config.onset_divisions
        )
        arranged, _t = enforce_monophony(arranged)
        fit = GridFit(
            step_ticks=float(tokenizer.ticks_per_step(480)),
            phase_ticks=0.0,
            aligned=True,
            period_sec=row_seconds(score.tempo_bpm),
        )
        rounded = enforce_monophony(
            tokenizer.decode(tokenizer.encode(arranged, fit=fit).ids).composition
        )[0]
        final, _repair = engine.apply(rounded)
        events = final.sounding_events()
        if not events:
            return None
        ticks = [e.tick for e in events]
        if min(ticks) < 0 or max(ticks) >= SECTION_BARS * bar_ticks:
            return None
        return final, {
            "termination": trimmed.reason,
            "tempo_bpm": score.tempo_bpm,
            "n_events": len(events),
            "decode": decode_report.to_dict(),
            "arrangement": arrange_report.to_dict(),
            "hardware_violations": len(engine.validate(final)),
        }

    def attempt(prompt_ids: list[int], *, label: str, base: int, offset: int):
        for tries in range(args.max_attempts):
            ids = generate(prompt_ids, seed=base + tries, offset=offset)
            built = to_nes(ids)
            if built is not None:
                return ids, built[0], {**built[1], "attempts": tries + 1}
            print(f"    {label}: attempt {tries + 1} invalid, retrying")
        return None, None, None

    # ---- compose ---------------------------------------------------------
    sections: list[Composition] = []
    records: list[dict[str, Any]] = []
    theme_prefix: list[int] | None = None
    failures: list[dict[str, Any]] = []

    for index, role in enumerate(roles):
        contrast = role == "B"
        header = build_header(
            vocab,
            plan,
            key_root=plan.key_root + CONTRAST_KEY_OFFSET if contrast else None,
        )
        if role == "A" or theme_prefix is None or contrast:
            prompt_ids = [vocab.id_of(t) for t in header]
            offset = 0
            origin = "fresh generation from the interpreted plan"
            if contrast:
                origin = (
                    f"fresh generation with the key moved to "
                    f"{plan.key_root + CONTRAST_KEY_OFFSET}:{plan.key_mode} "
                    "-- contrast comes from altered conditioning, the model "
                    "was not asked for a contrasting section"
                )
        else:
            prompt_ids = theme_prefix
            offset = 0
            origin = (
                f"continuation of section A's first {THEME_BARS} bars; "
                "bars 1-4 are A's material, bars 5-8 newly generated"
            )
        ids, section, report = attempt(
            prompt_ids, label=f"section {index + 1} ({role})",
            base=args.seed + index * 1000, offset=offset
        )
        if section is None:
            failures.append({"section": index + 1, "role": role})
            print(f"  section {index + 1} ({role}): FAILED after {args.max_attempts}")
            continue
        if role == "A" and theme_prefix is None:
            theme_prefix = bar_prefix(ids, vocab=vocab, n_bars=THEME_BARS)
        sections.append(section)
        records.append({"index": index + 1, "role": role, "origin": origin, **report})
        print(
            f"  section {index + 1} ({role:<3}) {report['n_events']:>4} events, "
            f"{report['attempts']} attempt(s) -- {origin[:58]}"
        )

    if not sections:
        print("error: no sections generated", file=sys.stderr)
        return 2

    track = concatenate(
        sections,
        bar_ticks=bar_ticks,
        section_bars=SECTION_BARS,
        bpm=records[0]["tempo_bpm"],
        beats_per_bar=plan.beats_per_bar,
    )
    # Monophony and hardware repair run on the ASSEMBLED track, not only per
    # section. Every section was individually valid and the concatenation
    # still produced five violations: a note whose duration runs past its
    # section's last bar line overlaps the next section's opening on a
    # monophonic channel, and there are four boundaries. Validating the whole
    # track without repairing it reported the problem instead of fixing it.
    loop_start, loop_end = track.loop_start_tick, track.loop_end_tick
    track, _truncated = enforce_monophony(track)
    track, seam_repairs = engine.apply(track)
    track.loop_start_tick, track.loop_end_tick = loop_start, loop_end
    violations = engine.validate(track)
    n_seam_repairs = len(seam_repairs) if isinstance(seam_repairs, list) else 0
    end = track.loop_end_tick or track.end_tick or 0
    duration = track.time.seconds(end)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    wav = args.out_dir / f"{args.name}.wav"
    render_window(track, wav)
    normalise_peak(wav, dbfs=PEAK_DBFS)
    midi_path = args.out_dir / f"{args.name}.mid"
    try:
        from rse.events.convert import composition_to_intake
        from rse.exporters.midi import record_to_midi

        record_to_midi(composition_to_intake(track, profile=profile)).save(str(midi_path))
    except Exception as error:  # noqa: BLE001 - reported, not fatal
        print(f"  midi export failed: {type(error).__name__}: {error}")
        midi_path = None

    plan.requirements.append(
        Requirement(
            f"{len(sections)} sections, {' '.join(r['role'] for r in records)}",
            "imposed",
            "section form chosen by the assembler",
        )
    )
    report = plan.report()
    payload = {
        "version": "rse-prompt-to-song/0.1",
        "prompt": args.prompt,
        "plan": plan.to_dict(),
        "form": [r["role"] for r in records],
        "section_bars": SECTION_BARS,
        "theme_bars": THEME_BARS,
        "total_bars": len(sections) * SECTION_BARS,
        "duration_sec": round(duration, 3),
        "requested_seconds": plan.target_seconds,
        "loop": {"start_tick": track.loop_start_tick, "end_tick": track.loop_end_tick},
        "hardware_violations": len(violations),
        "seam_repairs": n_seam_repairs,
        "seed": args.seed,
        "sampling": {
            "temperature": args.temperature,
            "top_k": args.top_k,
            "repetition_penalty": args.repetition_penalty,
        },
        "sections": records,
        "failed_sections": failures,
        "requirement_report": report,
        "files": {
            "wav": str(wav),
            "midi": str(midi_path) if midi_path else None,
        },
    }
    out_json = args.out_dir / f"{args.name}.json"
    out_json.write_text(json.dumps(payload, indent=2) + "\n")

    print(f"\n{'-' * 68}")
    print(f"duration {duration:.1f} s (requested {plan.target_seconds:g} s), "
          f"{len(sections) * SECTION_BARS} bars, {len(violations)} hardware violations "
          f"({n_seam_repairs} seam repairs applied)")
    print(f"loop: tick {track.loop_start_tick} -> {track.loop_end_tick}")
    print("\nrequirement report")
    for status in ("satisfied", "approximated", "imposed", "unsupported"):
        items = report.get(status, [])
        print(f"  {status.upper()} ({len(items)})")
        for item in items:
            print(f"    - {item['text']}: {item['detail']}")
    print(f"\nwrote {wav}")
    if midi_path:
        print(f"wrote {midi_path}")
    print(f"wrote {out_json}")
    print(
        "\nv0.1 makes no claim that this sounds good. It claims the track is "
        "complete, hardware-valid, the requested length, and honestly described."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
