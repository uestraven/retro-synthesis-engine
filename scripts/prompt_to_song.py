"""Prompt-to-Song v0.1: free text in, a complete NES track out.

End to end: a written request becomes a plan the composer can take, the
composer writes the musical material, the assembler builds a full-length form
out of it, and the existing corrected pipeline renders it as hardware-valid
NES audio.

The form is A A' B A'', each section eight bars:

- **A** is generated fresh from the plan's conditioning.
- **A'** and **A''** are generated by handing the model A's first four bars as
  a prefix and letting it continue. So the returning material is genuinely
  re-composed around the same opening rather than pasted -- the mechanism
  validated in `scripts/theme_bank.py`, where every prefix resumed cleanly at
  the next bar.
- **B** is generated fresh with a deliberately altered key, which is what
  makes it contrast. The model is not asked for "a contrasting section"; it
  cannot be. The contrast comes from changing its conditioning.

**What is generated and what is imposed is reported, not blurred.** The
composer never receives "contrasting middle section", "return to the main
theme" or "loopable". Those are structural decisions this script makes. The
report separates requirements that were satisfied, approximated, imposed by
the assembler, and simply unsupported -- and "memorable melody" is always in
the last group, because nothing anywhere in this pipeline takes memorability
as an input.

The loop is a real boundary rather than a fade: the track is rendered to end
exactly at the final bar line with the loop points recorded, so the last bar
runs straight into the first.

v0.1 does not claim the output is good. It claims the output is complete,
hardware-valid, the requested length, and honestly described.
"""

