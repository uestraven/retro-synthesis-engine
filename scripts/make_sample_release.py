#!/usr/bin/env python3
"""Build a synthetic dataset release so the pipeline can be run end to end.

NES-MDB is not redistributable, so this produces a small stand-in archive with
the same shape. Use it to smoke-test acquisition, normalization and reporting
before (or without) downloading the real dataset:

    python scripts/make_sample_release.py
    rse fetch  --dataset rse_sample --release midi --archive datasets/sample/rse_sample_midi.tar.gz
    rse ingest --dataset rse_sample --release midi
    rse inspect --dataset rse_sample --release midi
"""

from __future__ import annotations

import argparse
from pathlib import Path

from rse import paths
from rse.data.synthetic import make_sample_release
from rse.jsonio import write_json

#: Written next to the real dataset definitions so `rse fetch` can find it.
SAMPLE_CONFIG = {
    "schema_version": "rse-dataset/0.1.0",
    "dataset_id": "rse_sample",
    "display_name": "RSE synthetic sample release",
    "homepage": "",
    "use_class": "commercially_cleared",
    "license_note": "Generated by scripts/make_sample_release.py; no third-party content.",
    "releases": {
        "midi": {
            "release_id": "midi",
            "description": "Synthetic four-channel MIDI for pipeline smoke tests.",
            "url": None,
            "sha256": None,
            "archive_name": "rse_sample_midi.tar.gz",
            "file_globs": ["**/*.mid"],
            "expected_splits": ["train", "valid", "test"],
            "split_is_composer_disjoint": False,
        }
    },
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--dest",
        type=Path,
        default=paths.DATASETS_DIR / "sample",
        help="where to write the archive",
    )
    parser.add_argument("--per-split", type=int, default=4)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    archive = make_sample_release(args.dest, n_per_split=args.per_split, seed=args.seed)
    config_path = write_json(paths.DATASET_CONFIGS_DIR / "rse_sample.json", SAMPLE_CONFIG)
    print(f"archive: {archive}")
    print(f"config : {config_path}")
    print(
        "\nnext:\n"
        f"  rse fetch  --dataset rse_sample --release midi --archive {archive} --overwrite\n"
        "  rse ingest --dataset rse_sample --release midi"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
